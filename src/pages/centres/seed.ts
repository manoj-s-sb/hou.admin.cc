export const seedBookings = (centreId: string): CentreBooking[] =>
  Array.from({ length: 8 }, (_, i) => ({
    id: `${centreId.toUpperCase()}-B${2001 + i}`,
    member: MEMBER_NAMES[i % MEMBER_NAMES.length],
    lane: LANES[i % LANES.length],
    date: `Jun ${1 + i}, 2026`,
    time: `${(8 + i) % 24}:00 – ${(9 + i) % 24}:00`,
    sessionType: SESSION_TYPES[i % SESSION_TYPES.length],
    status: BOOKING_STATUS[i],
  }));
