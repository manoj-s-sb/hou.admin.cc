export const seedMembers = (centreId: string): CentreMember[] =>
  MEMBER_NAMES.map((name, i) => ({
    id: `${centreId.toUpperCase()}-M${101 + i}`,
    name,
    email: `${name.toLowerCase().replace(/[^a-z]/g, '.')}@email.com`,
    plan: PLAN_POOL[i % PLAN_POOL.length],
    memberType: TYPE_POOL[i],
    joinDate: `Mar ${10 + i}, 2025`,
    bookings: ((i * 7 + 5) % 20) + 5,
    status: STATUS_POOL[i],
  }));

const LANES = ['Batting 1', 'Batting 2', 'Bowling 1', 'Multi-purpose 1', 'Batting 3'];
